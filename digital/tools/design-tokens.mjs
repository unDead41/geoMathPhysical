import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {LIGHT_TOKENS,DARK_TOKENS,STRONG_TOKENS,DARK_STRONG_TOKENS,MODULE_TOKENS,UI_TIMING,designTokenCss} from '../design-system/tokens.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const check=process.argv.includes('--check');
// This plain module is generated so the existing offline concatenator needs no
// dependency resolver, network request, CDN or runtime import of the token owner.
const adapter='// Generated by digital/tools/design-tokens.mjs. Do not edit.\n'+
  'export const CENTRAL_UI_TIMING=Object.freeze('+JSON.stringify(UI_TIMING,null,2)+');\n'+
  'export const CENTRAL_MODULE_TOKENS=Object.freeze('+JSON.stringify({...LIGHT_TOKENS,...MODULE_TOKENS},null,2)+');\n'+
  'export const CENTRAL_DARK_TOKENS=Object.freeze('+JSON.stringify(DARK_TOKENS,null,2)+');\n'+
  'export const CENTRAL_STRONG_TOKENS=Object.freeze('+JSON.stringify(STRONG_TOKENS,null,2)+');\n'+
  'export const CENTRAL_DARK_STRONG_TOKENS=Object.freeze('+JSON.stringify(DARK_STRONG_TOKENS,null,2)+');\n'+
  'export function centralModuleTokenCss(){return '+JSON.stringify(designTokenCss({module:true}))+';}\n';
const outputs={
  'dist/design-tokens.css':designTokenCss(),
  'dist/module-design.mjs':'// Generated by tools/design-tokens.mjs. Do not edit.\nexport const MODULE_DESIGN_CSS='+JSON.stringify(designTokenCss({module:true})+'\n'+fs.readFileSync(path.join(root,'dist/module-foundation.css'),'utf8'))+';\n',
  'module/src/central-tokens.mjs':adapter,
  'module/src/design-tokens.css':designTokenCss({module:true})
};
let stale=false;
for(const [relative,content] of Object.entries(outputs)){
  const target=path.join(root,relative);
  if(check){
    if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==content){console.error('STALE '+relative+' — run node tools/design-tokens.mjs');stale=true;}
  }else{fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,content);}
}
// Reject shadow token owners even when a developer regenerated every adapter.
// Local geometry values and preference variables are outside this shared set.
if(check){
  const owners=new Set(Object.keys(LIGHT_TOKENS));
  for(const relative of ['dist/style.css','dist/portal.css','dist/usability.css','dist/foundation.css','module/src/style.css','module/src/net-tools.css','dist/module-frame.mjs','dist/module-foundation.css']){
    const target=path.join(root,relative);if(!fs.existsSync(target))continue;
    const source=fs.readFileSync(target,'utf8');
    for(const match of source.matchAll(/--([\w-]+)\s*:\s*[^;{}]+/g)){
      if(owners.has(match[1])){console.error('TOKEN OWNER DRIFT '+relative+': --'+match[1]+' must be changed in design-system/tokens.mjs');stale=true;}
    }
  }
}
if(stale)process.exitCode=1;
else console.log(check?'PASS: portal/module token adapters match one canonical source.':'Generated portal CSS, offline module adapter and module CSS.');
