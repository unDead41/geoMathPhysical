#!/usr/bin/env node
/** Reproduce the native token adapter from the pinned canonical JS owner. */
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve, dirname} from 'node:path';
import {pathToFileURL} from 'node:url';

const args = process.argv.slice(2);
const source = args[0];
const sourceCommit = args[1];
const expectedBlob = '94a77935bf3b9c67cf6c5cd5766bc677858b58b4';
if (!source || !/^[a-f0-9]{40}$/.test(sourceCommit ?? '')) {
  throw new Error('Usage: node tools/design/export_tokens.mjs <canonical tokens.mjs> <source commit SHA>');
}
let bytes = await readFile(resolve(source));
const blobHash = data => createHash('sha1').update(`blob ${data.length}\0`).update(data).digest('hex');
// Some read-only source transports append one newline. Accept only the known
// canonical blob; never silently accept a changed design source.
if (blobHash(bytes) !== expectedBlob && bytes.at(-1) === 10) bytes = bytes.subarray(0, -1);
if (blobHash(bytes) !== expectedBlob) throw new Error('Canonical token blob differs from the approved source lock.');
const sourceHash = createHash('sha256').update(bytes).digest('hex');
const module = await import(pathToFileURL(resolve(source)).href);
const names = ['light', 'dark', 'strong', 'darkStrong'];
const configurations = [
  {theme:'light'}, {theme:'dark'},
  {theme:'light',contrast:'strong'}, {theme:'dark',contrast:'strong'},
];
const quote = value => `'${value.replaceAll('\\','\\\\').replaceAll("'", "\\'")}'`;
const maps = configurations.map((config, index) => {
  const values = module.effectiveTokens(config);
  const resolved = Object.fromEntries(Object.keys(values).sort().map(key => {
    let value = values[key];
    const seen = new Set();
    while (/^var\(--(.+)\)$/.test(value)) {
      if (seen.has(value)) throw new Error(`Circular alias ${key}`);
      seen.add(value);
      value = values[value.slice(6, -1)];
      if (value === undefined) throw new Error(`Unresolved alias ${key}`);
    }
    return [key, value];
  }));
  return `  static const ${names[index]} = <String, String>{\n${Object.entries(resolved).map(([key,value])=>`    ${quote(key)}: ${quote(value)},`).join('\n')}\n  };`;
});
const output = resolve('lib/core/design/design_tokens.g.dart');
const body = `// GENERATED by tools/design/export_tokens.mjs. Do not edit.\n// Canonical owner: digital/design-system/tokens.mjs\n// Source commit: ${sourceCommit}\n// Source Git blob: ${expectedBlob}\n// Source SHA-256: ${sourceHash}\n\nabstract final class DesignTokens {\n  static const version = ${module.DESIGN_SYSTEM_VERSION};\n  static const sourceCommit = '${sourceCommit}';\n  static const sourceBlob = '${expectedBlob}';\n  static const sourceSha256 = '${sourceHash}';\n${maps.join('\n\n')}\n}\n`;
await mkdir(dirname(output), {recursive:true});
await writeFile(output, body);
process.stdout.write(`Generated ${output} from ${expectedBlob}\n`);
